from datetime import datetime
from pathlib import Path
from typing import Union

from ctf_recon.models import TriageReport


def generate_markdown_report(report: TriageReport) -> str:
    """
    Generates a structured, clean CTF writeup triage report in Markdown format.
    """
    timestamp_str = (
        report.scan_timestamp.strftime("%Y-%m-%d %H:%M:%S UTC")
        if isinstance(report.scan_timestamp, datetime)
        else str(report.scan_timestamp)
    )

    lines = [
        f"# CTF Recon & Triage Report: `{report.target}`",
        "",
        "> Automated reconnaissance and triage report generated by `ctf-recon`.",
        "",
        "## Summary",
        f"- **Target:** `{report.target}`",
        f"- **Scan Timestamp:** {timestamp_str}",
        f"- **Open Ports Detected:** {len(report.open_ports)}",
        f"- **Web Endpoints Triaged:** {len(report.web_findings)}",
        f"- **Flags / Tokens Discovered:** {len(report.flags_found)}",
        "",
        "---",
        "",
        "## 1. Port Scan & Service Detection",
    ]

    if report.open_ports:
        lines.extend([
            "| Port | Protocol | State | Service / Banner |",
            "| :--- | :--- | :--- | :--- |",
        ])
        for p in report.open_ports:
            banner_clean = (p.banner or "-").replace("\n", " ").replace("|", "\\|")
            lines.append(f"| `{p.port}` | {p.protocol.upper()} | **{p.state}** | `{banner_clean}` |")
    else:
        lines.append("_No open ports were detected on this target._")

    lines.extend([
        "",
        "---",
        "",
        "## 2. Web Application Triage",
    ])

    if report.web_findings:
        for web in report.web_findings:
            lines.extend([
                f"### Target Endpoint: `{web.url}`",
                f"- **Status Code:** `{web.status_code}`",
                f"- **Server:** `{web.server_header or 'Not Disclosed'}`",
                f"- **X-Powered-By:** `{web.x_powered_by or 'Not Disclosed'}`",
                f"- **Routes Inspected:** {', '.join(f'`{r}`' for r in web.routes_checked) if web.routes_checked else 'None'}",
            ])
            if web.redirects:
                lines.append(f"- **Redirect Chain:** {' -> '.join(web.redirects)}")

            if web.findings:
                lines.append("- **Findings:**")
                for f in web.findings:
                    lines.append(f"  - {f}")
            lines.append("")
    else:
        lines.append("_No web applications were detected or triaged._")

    lines.extend([
        "---",
        "",
        "## 3. Discovered Flags & Artifacts",
    ])

    if report.flags_found:
        lines.extend([
            "| Type | Flag / Decoded Token | Source |",
            "| :--- | :--- | :--- |",
        ])
        for flag in report.flags_found:
            clean_flag = flag.flag_text.replace("|", "\\|")
            lines.append(f"| `{flag.format_type}` | **`{clean_flag}`** | `{flag.source}` |")
    else:
        lines.append("_No flags or suspicious decoded Base64 tokens were discovered._")

    lines.extend([
        "",
        "---",
        "",
        "## 4. AI Strategic Analysis & Next Steps",
    ])

    if report.ai_analysis:
        ai = report.ai_analysis

        if ai.service_criticality:
            lines.extend([
                "### Service Criticality Assessment",
                "| Service / Port | Criticality Level |",
                "| :--- | :--- |",
            ])
            for svc, crit in ai.service_criticality.items():
                lines.append(f"| `{svc}` | **{crit}** |")
            lines.append("")

        if ai.probable_cves:
            lines.extend([
                "### Probable CVEs & Known Weaknesses",
            ])
            for cve in ai.probable_cves:
                lines.append(f"- **{cve}**")
            lines.append("")

        if ai.suggested_cli_commands:
            lines.extend([
                "### Suggested Follow-up Commands",
                "```bash",
            ])
            for cmd in ai.suggested_cli_commands:
                lines.append(cmd)
            lines.extend([
                "```",
                "",
            ])

        if ai.attack_vectors:
            lines.extend([
                "### Recommended Attack Vectors & Angles",
            ])
            for vector in ai.attack_vectors:
                lines.append(f"- {vector}")
            lines.append("")
    else:
        lines.append("_AI analysis was not enabled for this scan or no recommendations were generated._")

    lines.append("")
    return "\n".join(lines)


def export_report_to_markdown(report: TriageReport, output_path: Union[str, Path] = "writeup_triage.md") -> str:
    """
    Exports a TriageReport object to a Markdown writeup file.
    Creates necessary directories and returns the resolved file path as a string.
    """
    content = generate_markdown_report(report)
    target_path = Path(output_path)
    target_path.parent.mkdir(parents=True, exist_ok=True)
    target_path.write_text(content, encoding="utf-8")
    return str(target_path.resolve())
